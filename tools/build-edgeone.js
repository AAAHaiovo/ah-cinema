'use strict';

/*
 * 把 EdgeOne 入口、server/ 和 express 打包成一个自包含的 Node 函数文件。
 * 产物：cloud-functions/api/[[default]].js
 *
 * 用法：npm run build:edgeone
 */

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const outfile = path.join(root, 'cloud-functions', 'api', '[[default]].js');

let esbuild;
try {
  esbuild = require('esbuild');
} catch (error) {
  if (fs.existsSync(outfile)) {
    console.warn('[edgeone] 未安装 esbuild，使用已提交的打包文件：' + outfile);
    process.exit(0);
  }
  console.error('[edgeone] 缺少 esbuild，请先运行 npm install');
  process.exit(1);
}

fs.mkdirSync(path.dirname(outfile), { recursive: true });

esbuild.buildSync({
  entryPoints: [path.join(__dirname, 'edgeone-entry.js')],
  outfile,
  bundle: true,
  platform: 'node',
  target: 'node20',
  format: 'cjs',
  minify: false,
  sourcemap: false,
  legalComments: 'eof',
  banner: {
    js: '/* Generated by tools/build-edgeone.js. Do not edit by hand. */'
  }
});

console.log('[edgeone] 已生成 ' + outfile + '（' + fs.statSync(outfile).size + ' 字节）');
